export function asl42Sign(label, fields) {
  return {
    label,
    handshape: fields.handshape,
    palmOrientation: fields.palmOrientation,
    movement: fields.movement,
    nonManualMarkers: fields.nonManualMarkers,
    commonMistake: fields.commonMistake,
    source: fields.source,
    verification: fields.verification || WRITTEN_REFERENCE
  };
}

