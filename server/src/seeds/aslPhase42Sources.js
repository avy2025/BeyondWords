export function asl42Source(key, note) {
  const source = ASL42_SOURCES[key];
  if (!source) throw new Error(`Unknown ASL 4.2 source key: ${key}`);
  return note ? { ...source, note } : { ...source };
}

export function asl42Sources(entries) {
  return entries.map(([key, note]) => asl42Source(key, note));
}

