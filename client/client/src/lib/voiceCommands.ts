/**
 * voiceCommands.ts — Deterministic, local recognition for Mr. Pineapple's
 * supported commands and spoken room codes. This is intentionally separate
 * from the Ollama intent API: common commands must work even when that service
 * is unavailable.
 */

export type LocalIntentAction = 'START_MEET' | 'JOIN_MEET';

export interface LocalIntent {
  action: LocalIntentAction;
  password: string | null;
  message: null;
}

/**
 * Lowercase, strip basic punctuation, collapse whitespace and normalize the
 * two spellings of "let's". Diacritics are folded so transcript variants such
 * as "café" do not affect matching.
 */
export function normalizeTranscript(text: string | null | undefined): string {
  return String(text ?? '')
    .toLowerCase()
    .normalize('NFKD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/[\u2018\u2019\u201b`\u00b4]/g, "'")
    .replace(/[^a-z0-9'\s]/g, ' ')
    .replace(/\blets\b/g, "let's")
    .replace(/[']+/g, "'")
    .replace(/\s+/g, ' ')
    .trim();
}

const START_MEET_PATTERNS: RegExp[] = [
  /^(?:please\s+)?start\s+(?:the\s+|a\s+|a\s+new\s+|new\s+)?meeting(?:\s+now)?(?:\s+please)?$/,
  /^(?:let's\s+)?start\s+(?:the\s+|a\s+)?meeting(?:\s+now)?(?:\s+please)?$/,
  /^(?:let's\s+)?(?:please\s+)?start\s+(?:the\s+|a\s+)?meeting(?:\s+now)?(?:\s+please)?$/,
  /^(?:can|could|will|would)\s+you\s+(?:please\s+)?start\s+(?:the\s+|a\s+)?meeting(?:\s+now)?(?:\s+please)?$/,
  /^let's\s+start\s+(?:the\s+|a\s+)?meeting(?:\s+now)?(?:\s+please)?$/,
  /^i\s+(?:want|would like)\s+to\s+start\s+(?:the\s+|a\s+)?meeting(?:\s+now)?$/,
  /^(?:please\s+)?create\s+(?:the\s+|a\s+|a\s+new\s+|new\s+)?meeting(?:\s+now)?(?:\s+please)?$/,
  /^(?:let's\s+)?(?:please\s+)?create\s+(?:the\s+|a\s+)?meeting(?:\s+now)?(?:\s+please)?$/,
  /^(?:can|could|will|would)\s+you\s+(?:please\s+)?create\s+(?:the\s+|a\s+)?meeting(?:\s+now)?(?:\s+please)?$/,
  /^i\s+(?:want|would like)\s+to\s+create\s+(?:the\s+|a\s+)?meeting(?:\s+now)?$/,
];

const JOIN_MEET_PATTERNS: RegExp[] = [
  /^(?:please\s+)?(?:join|enter)\s+(?:the\s+|a\s+|an\s+)?meeting\b/,
  /^(?:please\s+)?(?:join|enter)\s+(?:the\s+|a\s+)?room\b/,
  /^(?:let's\s+)?(?:please\s+)?join\s+(?:the\s+|a\s+)?(?:meeting|room)\b/,
  /^(?:can|could|will|would)\s+you\s+(?:please\s+)?join\s+(?:the\s+|a\s+)?(?:meeting|room)\b/,
  /^i\s+(?:want|would like)\s+to\s+join\s+(?:the\s+|a\s+)?(?:meeting|room)\b/,
];

/**
 * Returns a local intent for phrases we always support. Returns null for
 * everything else so the existing Ollama/intent architecture remains in use.
 */
export function matchVoiceCommand(text: string | null | undefined): LocalIntent | null {
  const normalized = normalizeTranscript(text);
  if (!normalized) return null;

  if (START_MEET_PATTERNS.some((pattern) => pattern.test(normalized))) {
    return { action: 'START_MEET', password: null, message: null };
  }

  if (JOIN_MEET_PATTERNS.some((pattern) => pattern.test(normalized))) {
    return { action: 'JOIN_MEET', password: null, message: null };
  }

  return null;
}

/**
 * Wake-phrase matching is deliberately narrower than the old `endsWith
 * 'pineapple'` check: an honorific must appear next to "pineapple". That keeps
 * unrelated speech such as "I like pineapple" from activating the assistant.
 */
export function matchesWakeWord(text: string | null | undefined): boolean {
  const normalized = normalizeTranscript(text)
    .replace(/\bmr\b/g, 'mister')
    .replace(/\bmrs\b/g, 'mister');

  return /(?:^|\s)(?:(?:hey|hello|hi)\s+)?(?:there\s+)?mister\s+pine(?:apple|\s+apple)(?:\s|$)/.test(
    normalized
  );
}

/** Generated room IDs are ten lowercase alphanumeric characters. */
export function isValidRoomCode(code: string | null | undefined): boolean {
  return /^[a-z0-9]{10}$/.test(String(code ?? '').trim().toLowerCase());
}

const SPOKEN_ROOM_CHARS: Record<string, string> = {
  zero: '0', one: '1', two: '2', three: '3', four: '4',
  five: '5', six: '6', seven: '7', eight: '8', nine: '9',

  a: 'a', bee: 'b', b: 'b', see: 'c', c: 'c', dee: 'd', d: 'd',
  e: 'e', ee: 'e', eff: 'f', f: 'f', gee: 'g', g: 'g',
  h: 'h', aitch: 'h', eye: 'i', i: 'i', jay: 'j', j: 'j',
  kay: 'k', k: 'k', ell: 'l', l: 'l', em: 'm', m: 'm',
  en: 'n', n: 'n', o: 'o', oh: 'o', pee: 'p', p: 'p',
  cue: 'q', kue: 'q', q: 'q', arr: 'r', r: 'r', ess: 's', s: 's',
  tee: 't', t: 't', u: 'u', you: 'u', vee: 'v', v: 'v',
  w: 'w', ex: 'x', x: 'x', why: 'y', y: 'y',
  zee: 'z', zed: 'z', z: 'z',
};

function spokenTokenToChars(token: string): string | null {
  if (Object.prototype.hasOwnProperty.call(SPOKEN_ROOM_CHARS, token)) {
    return SPOKEN_ROOM_CHARS[token];
  }
  // Already-transcribed groups such as "abc" or "1234567".
  if (/^[a-z0-9]+$/.test(token)) return token;
  return null;
}

/**
 * Converts a spoken room code into the same ten-character format generated by
 * startMeeting(). Returns null unless exactly ten valid characters are heard.
 *
 * Accepts "a b c one two...", "abc1234567", "room code abc1234567" and common
 * letter/word pronunciations such as "double u" or "zero".
 */
export function parseSpokenRoomCode(text: string | null | undefined): string | null {
  const cleaned = normalizeTranscript(text)
    .replace(
      /^(?:please\s+)?(?:join|open|enter)\s+(?:the\s+|a\s+)?(?:room|meeting)(?:\s+(?:code|id))?(?:\s+is)?\s*/,
      ''
    )
    .replace(/^(?:my\s+|the\s+)?(?:room\s+)?(?:code|id)\s+(?:is\s+)?/, '')
    .replace(/^(?:it(?:'s| is)|that(?:'s| is)|i heard|say|use)\s+/, '')
    .trim();

  if (!cleaned) return null;

  const tokens = cleaned.split(/\s+/);
  const chars: string[] = [];

  for (let i = 0; i < tokens.length; i += 1) {
    const token = tokens[i];

    // In spoken English "double u" is the letter w, not two u's.
    if (token === 'double' && tokens[i + 1] === 'u') {
      chars.push('w');
      i += 1;
      continue;
    }

    if (token === 'double' && i + 1 < tokens.length) {
      const doubled = spokenTokenToChars(tokens[i + 1]);
      if (doubled && doubled.length === 1) {
        chars.push(doubled, doubled);
        i += 1;
        continue;
      }
    }

    const converted = spokenTokenToChars(token);
    if (!converted) return null;
    chars.push(...converted.split(''));
  }

  const code = chars.join('').toLowerCase();
  return isValidRoomCode(code) ? code : null;
}
